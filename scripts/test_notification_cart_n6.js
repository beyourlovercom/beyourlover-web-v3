function assertResult(action,payload,before,after,expected,copy){
  const count=notifyCalls.length;
  const got=bridge.confirm({endpoint:action,payload,before,after});
  assert.equal(got,expected,action+' result mismatch');
  assert.equal(notifyCalls.length,count+(expected?1:0),action+' emission mismatch');
  if(expected) {
    const call=notifyCalls.at(-1);
    assert.equal(call.message,copy);
    assert.equal(call.type,'success');
    assert.equal(call.confirmed,true);
    assert.equal(call.context,'cart-drawer');
    assert(!call.message.includes('<'),'no untrusted Woo text');
  }
}
